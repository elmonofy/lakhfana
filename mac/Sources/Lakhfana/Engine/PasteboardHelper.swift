import AppKit

/// General pasteboard access: full backup/restore of the user's clipboard and marked writes that clipboard
/// managers skip (nspasteboard.org conventions). Call on the main thread.
enum PasteboardHelper {
    struct Snapshot {
        let items: [[(NSPasteboard.PasteboardType, Data)]]
    }

    static let transientType = NSPasteboard.PasteboardType("org.nspasteboard.TransientType")
    static let concealedType = NSPasteboard.PasteboardType("org.nspasteboard.ConcealedType")
    static let autoGeneratedType = NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType")

    private static let maxBackupBytes = 200 * 1024 * 1024
    private static var pb: NSPasteboard { return NSPasteboard.general }

    static var changeCount: Int { return pb.changeCount }

    static func backup() -> Snapshot {
        var all: [[(NSPasteboard.PasteboardType, Data)]] = []
        var total = 0
        for item in pb.pasteboardItems ?? [] {
            var entries: [(NSPasteboard.PasteboardType, Data)] = []
            for type in item.types {
                if type == transientType || type == concealedType || type == autoGeneratedType { continue }
                guard let data = item.data(forType: type) else { continue }
                total += data.count
                if total > maxBackupBytes { break }
                entries.append((type, data))
            }
            if !entries.isEmpty { all.append(entries) }
            if total > maxBackupBytes { break }
        }
        return Snapshot(items: all)
    }

    static func restore(_ snapshot: Snapshot) {
        pb.clearContents()
        if snapshot.items.isEmpty { return }
        var objects: [NSPasteboardItem] = []
        for (index, entries) in snapshot.items.enumerated() {
            let item = NSPasteboardItem()
            for (type, data) in entries {
                item.setData(data, forType: type)
            }
            // Clipboard managers already recorded the original; don't let them record it twice.
            if index == 0 { item.setData(Data(), forType: transientType) }
            objects.append(item)
        }
        pb.writeObjects(objects)
    }

    static func readString() -> String? {
        return pb.string(forType: .string)
    }

    /// Plain text, marked transient + concealed so clipboard history tools ignore it.
    @discardableResult
    static func setString(_ text: String) -> Bool {
        pb.clearContents()
        let item = NSPasteboardItem()
        item.setString(text, forType: .string)
        item.setData(Data(), forType: transientType)
        item.setData(Data(), forType: concealedType)
        item.setData(Data(), forType: autoGeneratedType)
        return pb.writeObjects([item])
    }

    /// True when an editor (VS Code and other Electron/Chromium editors) copied the whole line for an empty selection.
    static func isEmptySelectionLineCopy() -> Bool {
        let needles = [
            Data("\"isFromEmptySelection\":true".utf8),
            "\"isFromEmptySelection\":true".data(using: .utf16LittleEndian) ?? Data(),
        ]
        for item in pb.pasteboardItems ?? [] {
            for type in item.types {
                let raw = type.rawValue.lowercased()
                guard raw.contains("vscode") || raw.contains("chromium") || raw.contains("web-custom-data") else { continue }
                guard let data = item.data(forType: type) else { continue }
                for n in needles where !n.isEmpty {
                    if data.range(of: n) != nil { return true }
                }
            }
        }
        return false
    }
}
